'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const start=html.indexOf('function commitQueue(previous)');
const end=html.indexOf('function render()',start);
assert.ok(start>=0&&end>start,'queue commit helper exists');
const source=html.slice(start,end);
const build=new Function('deps','let {items,persist,render}=deps;'+source+';return {commitQueue,getItems:()=>items}');
let renders=0;
const failed=build({items:[{id:'changed'}],persist:()=>false,render:()=>renders++});
assert.equal(failed.commitQueue([{id:'original'}]),false);
assert.equal(failed.getItems()[0].id,'original');
assert.equal(renders,1);
const passed=build({items:[{id:'saved'}],persist:()=>true,render:()=>{throw Error('Unexpected render')}});
assert.equal(passed.commitQueue([{id:'original'}]),true);
assert.equal(passed.getItems()[0].id,'saved');
for(const guard of ["if(!commitQueue(previous))return;input.value=''","if(!commitQueue(previous))return;filter.value='all'","if(!commitQueue(previous))return;feedback.textContent='Local queue cleared.'"])assert.ok(html.includes(guard),'queue mutation guarded: '+guard);
console.log('Proposal persistence rollback and success tests passed');
