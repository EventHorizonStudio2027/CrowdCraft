'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const start=html.indexOf('function visibleProjects(){');
const end=html.indexOf('function draw(){',start);
assert.ok(start>0&&end>start,'Library filtering function must exist');
const filter={value:''},sort={value:'newest'};
const projects=[{name:'Zebra',updated:'2026-01-02'},{name:'alpha',updated:'2026-01-03'},{name:'Beta',updated:'2026-01-01'}];
const visibleProjects=new Function('projects','filter','sort',html.slice(start,end)+';return visibleProjects')(projects,filter,sort);
assert.deepEqual(visibleProjects().map(x=>x.name),['alpha','Zebra','Beta']);
sort.value='oldest';assert.deepEqual(visibleProjects().map(x=>x.name),['Beta','Zebra','alpha']);
sort.value='name';assert.deepEqual(visibleProjects().map(x=>x.name),['alpha','Beta','Zebra']);
filter.value='BE';assert.deepEqual(visibleProjects().map(x=>x.name),['Beta']);
filter.value='missing';assert.deepEqual(visibleProjects(),[]);
assert.equal(projects.length,3,'Sorting must not mutate saved project order');
assert.ok(html.includes("filter.addEventListener('input',draw)"));
assert.ok(html.includes("sort.addEventListener('change',draw)"));
assert.ok(html.includes('noResults.hidden=visible.length>0||!filter.value.trim()'));
console.log('Project library search and sort checks passed');
