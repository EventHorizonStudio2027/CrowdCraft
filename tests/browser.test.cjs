'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const { chromium } = require('playwright');

test('browser studio workflow: editor, snippets, project recovery and viewport', async () => {
  const html = fs.readFileSync('index.html', 'utf8');
  const server = http.createServer((req, res) => {
    if (/^\/assets\/[a-z0-9._-]+\.(svg|png|webp|jpg)$/i.test(req.url || '')) {
      const file = '.' + req.url;
      if (!fs.existsSync(file)) { res.writeHead(404); res.end('Asset not found'); return; }
      const ext = file.split('.').pop().toLowerCase();
      res.setHeader('Content-Type', ({svg:'image/svg+xml',png:'image/png',webp:'image/webp',jpg:'image/jpeg'})[ext]);
      res.end(fs.readFileSync(file));
      return;
    }
    if (!/^\/(?:\?[^#]*)?$/.test(req.url || '')) { res.writeHead(404); res.end('Not found'); return; }
    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.end(html);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser, page;
  try {
    browser = await chromium.launch({ headless: true });
    page = await browser.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('dialog', dialog => dialog.accept());
    await page.goto('http://127.0.0.1:' + server.address().port);
    for (const path of ['assets/logo.svg', 'assets/brand-wordmark.svg']) {
      const image = page.locator('img[src="' + path + '"]').first();
      assert.equal(await image.evaluate(el => el.complete && el.naturalWidth > 0), true, path + ' loads as a real image');
    }
    await page.keyboard.press('Control+k');
    assert.equal(await page.locator('#command-dialog').isVisible(), true, 'command palette opens');
    await page.locator('#command-search').fill('Open studio');
    await page.locator('#command-search').press('Enter');
    assert.equal(await page.locator('#studio-view').isVisible(), true, 'command palette navigates');
    const editor = page.locator('#source');
    assert.ok((await editor.inputValue()).length > 0, 'starter loads');
    await editor.fill('alpha\nbeta');
    await page.locator('#editor-line').fill('2');
    await page.locator('#editor-go-line').click();
    assert.match(await page.locator('#editor-selection').innerText(), /Line 2/);
    await editor.fill('alpha\nbeta');
    await editor.evaluate(el => el.setSelectionRange(0,0));
    await page.locator('#editor-indent').click();
    assert.match(await editor.inputValue(), /^  alpha/);
    await page.locator('#editor-outdent').click();
    assert.match(await editor.inputValue(), /^alpha/);
    await page.locator('#reset').click();
    await page.locator('[data-snippet="loop"]').click();
    const source = await editor.inputValue();
    assert.ok(source.includes('\n'), 'inserted snippet contains real line breaks');
    assert.ok(!source.includes('\\n  '), 'snippet does not contain literal newline escapes');
    await page.locator('#editor-find').fill('script');
    assert.match(await page.locator('#find-status').innerText(), /match/);
    await page.locator('#preview-pause').click();
    assert.equal(await page.locator('#preview-pause').getAttribute('aria-pressed'), 'true');
    const pausedHtml = await page.locator('#preview').evaluate(el => el.srcdoc);
    await editor.fill('<!doctype html><title>Paused update</title><p>Paused update</p>');
    await page.waitForTimeout(500);
    assert.equal(await page.locator('#preview').evaluate(el => el.srcdoc), pausedHtml, 'paused preview remains unchanged');
    await page.locator('#preview-refresh').click();
    assert.match(await page.locator('#preview').evaluate(el => el.srcdoc), /Paused update/, 'manual refresh renders latest source');
    await page.waitForFunction(() => !document.getElementById('preview-refresh').hasAttribute('aria-busy'));
    assert.equal(await page.locator('#preview-refresh').getAttribute('aria-busy'), null, 'refresh progress resets when iframe loads');
    await page.locator('#preview-pause').click();
    assert.equal(await page.locator('#preview-pause').getAttribute('aria-pressed'), 'false');
    await editor.fill(source);
    await page.locator('#preview-expand').click();
    assert.equal(await page.locator('#preview-expand').getAttribute('aria-expanded'), 'true');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#preview-expand').getAttribute('aria-expanded'), 'false');
    await page.locator('[data-width="390px"]').click();
    assert.equal(await page.locator('#preview').evaluate(el => el.style.width), '390px');
    await page.locator('#snapshot-save').click();
    assert.match(await page.locator('#snapshot-status').innerText(), /saved/i);
    await page.locator('[data-view="projects"]').click();
    await page.locator('#project-name').fill('Browser test project');
    await page.locator('#project-save').click();
    assert.match(await page.locator('#project-list').innerText(), /Browser test project/);
    await page.locator('#project-filter').fill('not-a-match');
    assert.match(await page.locator('#project-count').innerText(), /0 of 1/);
    await page.locator('#project-filter').fill('Browser test');
    assert.match(await page.locator('#project-count').innerText(), /1 of 1/);
    await page.locator('#project-sort').selectOption('name');
    await page.locator('[data-view="studio"]').click();
    await editor.fill('<!doctype html><title>Changed</title><h1>Changed</h1>');
    await page.locator('[data-view="projects"]').click();
    await page.locator('#project-list button').first().click();
    assert.equal(await page.locator('#studio-view').isVisible(), true, 'restoring a project opens Studio');
    assert.equal(await editor.inputValue(), source);
    await page.locator('[data-view="studio"]').click();
    await page.locator('#editor-focus').click();
    assert.equal(await page.locator('#editor-focus').getAttribute('aria-pressed'), 'true');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#editor-focus').getAttribute('aria-pressed'), 'false', 'Escape exits focus mode');
    await page.locator('#visual-builder summary').click();
    await page.locator('#builder-title').fill('Visual Builder Test');
    const beforeGeneration = await editor.inputValue();
    await page.locator('#builder-generate').click();
    assert.match(await editor.inputValue(), /Visual Builder Test/, 'visual builder generated source');
    await page.locator('#builder-undo').click();
    assert.equal(await editor.inputValue(), beforeGeneration, 'undo restores source before generation');
    await page.locator('#builder-undo').click();
    assert.match(await editor.inputValue(), /Visual Builder Test/, 'undo toggles generated source back');
    assert.match(await page.locator('#builder-status').innerText(), /restored/i);
    await page.waitForTimeout(450);
    const savedDraft = await editor.inputValue();
    await page.reload();
    await page.locator('[data-view="studio"]').click();
    assert.equal(await page.locator('#source').inputValue(), savedDraft, 'autosaved draft survives reload');
    await page.locator('[data-view="projects"]').click();
    assert.match(await page.locator('#project-list').innerText(), /Browser test project/, 'saved library survives reload');
    await page.locator('[data-view="studio"]').click();
    await editor.fill('<!doctype html><h1>Repeated</h1><h1>Repeated</h1>');
    await page.locator('#text-inspector').evaluate(el => el.open = false);
    await page.locator('#text-inspector summary').click();
    await page.locator('#inspector-pick').click();
    await page.locator('#preview-refresh').click();
    await page.frameLocator('#preview').locator('h1').nth(1).click();
    await page.waitForFunction(expected => document.getElementById('inspector-target').value === expected, '1', {timeout: 5000});
    assert.equal(await page.locator('#inspector-target').inputValue(), '1', 'duplicate text selects clicked occurrence');
    await page.evaluate(() => window.dispatchEvent(new MessageEvent('message', {source: document.getElementById('preview').contentWindow, origin: 'https://untrusted.example', data: {type:'crowd-text-pick',tag:'h1',text:'Repeated',occurrence:0}})));
    assert.equal(await page.locator('#inspector-target').inputValue(), '1', 'picker ignores forged non-sandbox-origin messages');
    assert.equal(await page.locator('#inspector-picked').getAttribute('data-selected'), 'true', 'selected element chip confirms active selection');
    assert.match(await page.locator('#inspector-picked').getAttribute('title'), /^Source line \d+$/, 'selected element exposes its source line');
    await page.frameLocator('#preview').locator('h1[data-crowd-picked]').waitFor();
    assert.equal(await page.frameLocator('#preview').locator('h1').nth(1).getAttribute('data-crowd-picked'), '', 'clicked duplicate receives selection highlight');
    assert.equal(await page.frameLocator('#preview').locator('h1').first().getAttribute('data-crowd-picked'), null, 'other duplicate is not highlighted');
    await page.locator('#inspector-target').selectOption('0');
    await page.frameLocator('#preview').locator('h1:first-of-type[data-crowd-picked]').waitFor();
    assert.equal(await page.frameLocator('#preview').locator('h1').first().getAttribute('data-crowd-picked'), '', 'first duplicate can be selected separately');
    assert.equal(await page.frameLocator('#preview').locator('h1').nth(1).getAttribute('data-crowd-picked'), null, 'second duplicate clears when first is selected');
    await page.locator('#inspector-target').selectOption('1');
    await page.locator('#preview-refresh').click();
    await page.frameLocator('#preview').locator('h1').nth(1).waitFor();
    assert.equal(await page.locator('#inspector-target').inputValue(), '1', 'preview refresh preserves selected duplicate');
    await page.frameLocator('#preview').locator('h1').nth(1).waitFor({state:'visible'});
    await page.waitForTimeout(150);
    assert.equal(await page.frameLocator('#preview').locator('h1').nth(1).getAttribute('data-crowd-picked'), '', 'preview refresh restores duplicate highlight');
    await editor.fill('<!doctype html><h1>Updated while picking</h1>');
    assert.equal(await page.locator('#inspector-pick').getAttribute('aria-pressed'), 'false', 'source edit automatically exits stale picking mode');
    assert.equal(await page.locator('#preview-pick-banner').isHidden(), true, 'stale pick banner disappears');
    await page.locator('#text-inspector').evaluate(el => el.open = false);
    await editor.fill('<!doctype html><title>Test</title><h1>Old heading</h1><p>Old paragraph</p>');
    await page.locator('#text-inspector summary').click();
    await page.locator('#inspector-pick').click();
    await page.locator('#preview-refresh').click();
    await page.frameLocator('#preview').locator('h1').click();
    await page.waitForFunction(expected => document.getElementById('inspector-target').value === expected, '0', {timeout: 5000});
    assert.equal(await page.locator('#inspector-target').inputValue(), '0', 'preview click selects heading');
    await page.locator('#inspector-pick').click();
    await page.locator('#inspector-target').selectOption('0');
    assert.equal(await page.locator('#inspector-count').innerText(), '1 / 2', 'inspector displays selection count');
    await page.locator('#inspector-next').click();
    assert.equal(await page.locator('#inspector-target').inputValue(), '1', 'next selects following element');
    await page.locator('#inspector-prev').click();
    assert.equal(await page.locator('#inspector-target').inputValue(), '0', 'previous restores prior element');
    await page.frameLocator('#preview').locator('h1[data-crowd-picked]').waitFor();
    assert.equal(await page.frameLocator('#preview').locator('h1').first().getAttribute('data-crowd-picked'), '', 'dropdown selection highlights matching preview element');
    await page.locator('#inspector-apply').click();
    assert.equal(await page.locator('#inspector-undo').isDisabled(), true, 'unchanged inspector apply does not create undo history');
    assert.match(await page.locator('#inspector-status').innerText(), /No changes to apply/, 'unchanged inspector apply gives clear feedback');
    await page.locator('#inspector-value').fill('New <safe> & clear');
    await page.locator('#inspector-color').fill('#18c9e8');
    await page.locator('#inspector-size').fill('28');
    await page.locator('#inspector-align').selectOption('center');
    await page.locator('#inspector-weight').selectOption('700');
    await page.locator('#inspector-padding').fill('12');
    await page.locator('#inspector-radius').fill('8');
    await page.locator('#inspector-background').fill('#16324a');
    await page.locator('#inspector-apply').click();
    assert.match(await editor.inputValue(), /New &lt;safe&gt; &amp; clear/, 'inspector safely updates source text');
    assert.match(await editor.inputValue(), /color: #18c9e8/, 'inspector saves chosen color');
    assert.match(await editor.inputValue(), /font-size: 28px/, 'inspector saves chosen font size');
    assert.match(await editor.inputValue(), /text-align: center/, 'inspector saves text alignment');
    assert.match(await editor.inputValue(), /font-weight: 700/, 'inspector saves font weight');
    assert.match(await editor.inputValue(), /padding: 12px/, 'inspector saves padding');
    assert.match(await editor.inputValue(), /border-radius: 8px/, 'inspector saves corner radius');
    assert.match(await editor.inputValue(), /background-color: #16324a/, 'inspector saves background color');
    assert.equal(await page.locator('#inspector-target').inputValue(), '0', 'selection remains active after apply');
    assert.equal(await page.locator('#inspector-apply').isDisabled(), false, 'inspector remains ready for another edit');
    await page.locator('#inspector-refresh').click();
    assert.equal(await page.locator('#inspector-picked').getAttribute('data-selected'), 'false', 'rescan clears selected-element chip');
    assert.equal(await page.locator('#inspector-picked').getAttribute('title'), 'No element selected', 'rescan clears source line tooltip');
    await page.locator('#inspector-target').selectOption('0');
    await page.locator('#inspector-value').fill('Second revision');
    await page.locator('#inspector-apply').click();
    const revisedSource = await editor.inputValue();
    assert.match(revisedSource, /Second revision/, 'inspector edits existing styled elements');
    assert.equal((revisedSource.match(/style=/g) || []).length, 1, 'inspector does not duplicate inline style attributes');
    assert.match(revisedSource, /padding: 12px/, 'text-only edits preserve existing padding');
    assert.match(revisedSource, /border-radius: 8px/, 'text-only edits preserve existing corner radius');
    assert.match(revisedSource, /background-color: #16324a/, 'text-only edits preserve existing background');
    await page.locator('#inspector-background').fill('#ffffff');
    await page.locator('#inspector-reset').click();
    assert.equal(await page.locator('#inspector-background').inputValue(), '#16324a', 'reset restores selected element background');
    assert.equal(await editor.inputValue(), revisedSource, 'reset does not mutate source');
    assert.equal(await page.locator('#inspector-undo').isDisabled(), false, 'undo available after visual edits');
    await page.keyboard.press('Control+Alt+z');
    assert.doesNotMatch(await editor.inputValue(), /Second revision/, 'undo restores source before last inspector edit');
    assert.match(await editor.inputValue(), /New &lt;safe&gt; &amp; clear/, 'undo retains preceding inspector revision');
    assert.equal(await page.locator('#inspector-undo').isDisabled(), true, 'single-step undo cannot repeat');
    const longText = 'Long preview text '.repeat(30);
    await editor.fill('<!doctype html><p>' + longText + '</p>');
    await page.locator('#inspector-pick').click();
    await page.locator('#preview-refresh').click();
    await page.frameLocator('#preview').locator('p').click();
    await page.waitForFunction(() => document.getElementById('inspector-target').value === '0', null, {timeout: 5000});
    assert.equal(await page.locator('#inspector-target').inputValue(), '0', 'long preview text remains selectable');
    assert.equal(await page.locator('#inspector-value').inputValue(), longText, 'long preview selection retains full text');
    await page.locator('#inspector-pick').click();
    await page.locator('#reset').click();
    assert.match(await page.locator('#source').inputValue(), /Quick Notes|Star Catcher/i, 'reset loads starter');
    assert.match(await page.locator('#save-indicator').innerText(), /Saved locally/);
    assert.deepEqual(errors, [], 'no page errors');
  } catch (error) {
    if (page) {
      try { fs.mkdirSync('test-artifacts', { recursive: true }); await page.screenshot({ path: 'test-artifacts/browser-failure.png', fullPage: true }); fs.writeFileSync('test-artifacts/error.txt', String(error.stack || error) + '\nURL: ' + page.url() + '\n'); } catch {}
    }
    throw error;
  } finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
  }
});
